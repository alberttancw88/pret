// Generates the W2-003 synthetic employee block of supabase/seed.sql (dev / staging only — PDPA).
// MyKad numbers are synthetic (valid format, serial 0001–0008) and are encrypted with THIS environment's
// field key exactly as the app does (ADR-0003: AES-256-GCM, AAD table:column:rowId, HMAC blind index),
// so the ciphertext in seed.sql is only usable with the key it was generated with. Regenerate per environment:
//   node --env-file=.env.local supabase/seed/w2_003_employees.mjs > /tmp/w2_003_seed.sql
// The script never prints key material or plaintext MyKad numbers.
import { registerHooks } from 'node:module';

registerHooks({
  resolve(specifier, context, next) {
    try { return next(specifier, context); } catch (e) {
      if (specifier.startsWith('.') && !/\.[cm]?[jt]s$/.test(specifier)) return next(`${specifier}.ts`, context);
      throw e;
    }
  },
});
const fc = await import('../../src/server/crypto/field-crypto.ts');

const raw = process.env.PRET_FIELD_KEY_V1;
if (!raw) { console.error('PRET_FIELD_KEY_V1 is not set'); process.exit(2); }
const v1 = fc.parseKey(raw, 'PRET_FIELD_KEY_V1');
const ring = { currentKeyId: 1, keys: new Map([[1, v1]]), blindIndexKey: process.env.PRET_BLIND_INDEX_KEY ? fc.parseKey(process.env.PRET_BLIND_INDEX_KEY, 'PRET_BLIND_INDEX_KEY') : fc.deriveBlindIndexKey(v1) };
const hex = (b) => `'\\x${b.toString('hex')}'`;

// Fixed ids so the block is idempotent (on conflict do nothing).
const id = (n) => `00000000-0000-4000-8000-0000000e00${String(n).padStart(2, '0')}`;
const spouseId = '00000000-0000-4000-8000-0000000e5001';
const childId = '00000000-0000-4000-8000-0000000ec001';

// no, name, gender, dob(YYMMDD → mykad), join offset (days from today), probation, manager index, position, grade, extra
const people = [
  { n: 1, name: 'Sample Employee One',   g: 'male',   dob: '800101', join: -2400, prob: 0, mgr: null, pos: 'SMPCEO', grade: 'SMP3', top: true },
  { n: 2, name: 'Sample Employee Two',   g: 'female', dob: '850202', join: -1800, prob: 0, mgr: 1, pos: 'SMPMGR', grade: 'SMP2' },
  { n: 3, name: 'Sample Employee Three', g: 'male',   dob: '900303', join: -900,  prob: 0, mgr: 2, pos: 'SMPENG', grade: 'SMP1', married: true },
  { n: 4, name: 'Sample Employee Four',  g: 'female', dob: '920404', join: -400,  prob: 3, mgr: 2, pos: 'SMPENG', grade: 'SMP1', confirmed: true },
  { n: 5, name: 'Sample Employee Five',  g: 'male',   dob: '950505', join: -40,   prob: 3, mgr: 3, pos: 'SMPENG', grade: 'SMP1' },
  { n: 6, name: 'Sample Employee Six',   g: 'female', dob: '960606', join: 21,    prob: 3, mgr: 2, pos: 'SMPENG', grade: 'SMP1' },
  { n: 7, name: 'Sample Employee Seven', g: 'male',   dob: '970707', join: -700,  prob: 0, mgr: 2, pos: 'SMPENG', grade: 'SMP1', leaving: true },
  { n: 8, name: 'Sample Employee Eight', g: 'female', dob: '980808', join: -100,  prob: 3, mgr: 1, pos: 'SMPADM', grade: 'SMP1' },
];

const sqlLines = [];
const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
sqlLines.push(`-- ---------------------------------------------------------------------------
-- W2-003 (synthetic): sample grades, positions and 8 sample employees (employee no. SMP-01 … SMP-08).
-- Generated by supabase/seed/w2_003_employees.mjs — MyKad ciphertext is valid only with the key of the
-- environment it was generated for (pret-dev). No real person; emails are @example.com.
-- ---------------------------------------------------------------------------
insert into app.grades (code, name, rank) values ('SMP1', 'Sample grade 1', 101), ('SMP2', 'Sample grade 2', 102), ('SMP3', 'Sample grade 3', 103)
on conflict (code) do nothing;
insert into app.positions (code, title) values ('SMPCEO', 'Sample Director'), ('SMPMGR', 'Sample Manager'), ('SMPENG', 'Sample Engineer'), ('SMPADM', 'Sample Administrator')
on conflict (code) do nothing;

do $$
declare v_dept uuid; v_loc uuid; v_pat uuid; v_today date := app.today_myt();
begin
  if exists (select 1 from app.employees where employee_no = 'SMP-01') then return; end if;
  select id into v_dept from app.departments where code = 'DEV' or is_active order by (code = 'DEV') desc, code limit 1;
  select id into v_loc from app.work_locations where is_active order by name limit 1;
  select id into v_pat from app.working_patterns where is_active order by name limit 1;
  perform set_config('app.actor_label', 'system:seed', true);`);

for (const p of people) {
  const mykad = `${p.dob}14${String(p.n).padStart(4, '0').slice(0, 3)}${p.g === 'male' ? 1 : 2}`;
  const enc = fc.encryptField(ring, mykad, { table: 'employee_personal', column: 'nric_enc', rowId: id(p.n) });
  const bidx = fc.blindIndex(ring, 'nric', mykad);
  const yy = Number(p.dob.slice(0, 2));
  const dob = `${yy > 30 ? 19 : 20}${p.dob.slice(0, 2)}-${p.dob.slice(2, 4)}-${p.dob.slice(4, 6)}`;
  const no = `SMP-0${p.n}`;
  const mgr = p.mgr ? `'${id(p.mgr)}'::uuid` : 'null';
  sqlLines.push(`
  insert into app.employees (id, employee_no, full_name, gender, work_email, mobile_phone, join_date, probation_months, department_id, position_id,
                             grade_id, manager_employee_id, work_location_id, work_state, working_pattern_id, status)
  values ('${id(p.n)}', '${no}', ${q(p.name)}, '${p.g}', 'sample${String(p.n).padStart(2, '0')}@example.com', '+6012000000${p.n}',
          v_today + ${p.join}, ${p.prob}, v_dept, (select id from app.positions where code = '${p.pos}'), (select id from app.grades where code = '${p.grade}'),
          ${mgr}, v_loc, 'SGR', v_pat, 'confirmed');
  insert into app.employee_personal (employee_id, nric_enc, nric_last4, nric_bidx, date_of_birth, personal_email, res_addr_line1, res_postcode, res_city,
                                     res_state, continuous_service_date, race, race_other, highest_qualification)
  values ('${id(p.n)}', ${hex(enc)}, '${mykad.slice(-4)}', ${hex(bidx)}, date '${dob}', 'sample${String(p.n).padStart(2, '0')}.home@example.com',
          '${p.n} Jalan Contoh', '40000', 'Shah Alam', 'SGR', v_today + ${p.join}, 'others', 'Sample', 'bachelor');
  insert into app.employee_sensitive (employee_id, religion) values ('${id(p.n)}', 'prefer_not_to_say');
  insert into app.employee_hr_private (employee_id, is_top_of_org) values ('${id(p.n)}', ${p.top ? 'true' : 'false'});
  insert into app.employee_statutory_profiles (employee_id, socso_category) values ('${id(p.n)}', 'category_1');
  insert into app.employee_statutory_employer_flags (employee_id) values ('${id(p.n)}');
  insert into app.employee_marital_history (employee_id, marital_status, effective_date)
  values ('${id(p.n)}', '${p.married ? 'married' : 'single'}', v_today + ${p.join});
  insert into app.employee_emergency_contacts (employee_id, priority, name, relationship, mobile_phone)
  values ('${id(p.n)}', 1, 'Sample Contact ${p.n}', 'parent', '+6013000000${p.n}');`);
  if (p.confirmed) sqlLines.push(`  perform app.refresh_employee_status('${id(p.n)}'); update app.employees set confirmation_date = v_today + ${p.join + 90} where id = '${id(p.n)}'; perform app.refresh_employee_status('${id(p.n)}');`);
  if (p.married) {
    const sk = `880303145001`;
    const se = fc.encryptField(ring, sk.slice(0, 11) + '2', { table: 'employee_spouses', column: 'nric_enc', rowId: spouseId });
    const sb = fc.blindIndex(ring, 'spouse_nric', sk.slice(0, 11) + '2');
    const ck = `150303141002`;
    const ce = fc.encryptField(ring, ck, { table: 'employee_children', column: 'nric_enc', rowId: childId });
    const cb = fc.blindIndex(ring, 'child_nric', ck);
    sqlLines.push(`  insert into app.employee_spouses (id, employee_id, full_name, nric_enc, nric_last4, nric_bidx, working_status, marriage_date)
  values ('${spouseId}', '${id(p.n)}', 'Sample Spouse Three', ${hex(se)}, '5002', ${hex(sb)}, 'not_working', v_today - 3000);
  insert into app.employee_children (id, employee_id, full_name, nric_enc, nric_last4, nric_bidx, date_of_birth, relationship, pcb_category, relief_share)
  values ('${childId}', '${id(p.n)}', 'Sample Child Three', ${hex(ce)}, '1002', ${hex(cb)}, date '2015-03-03', 'biological', 'under_18', 'full_100');`);
  }
  if (p.leaving) sqlLines.push(`  insert into app.employee_separations (id, employee_id, notice_date, separation_type, last_working_day)
  values ('00000000-0000-4000-8000-0000000e5e07', '${id(p.n)}', v_today - 10, 'resignation', v_today + 32);
  insert into app.employee_separation_details (separation_id, employee_id, reason_category, notice_required_days, notice_outcome, portal_access_end_date)
  values ('00000000-0000-4000-8000-0000000e5e07', '${id(p.n)}', 'career_advancement', 42, 'served', v_today + 32);`);
}
sqlLines.push(`
  update app.departments set head_employee_id = '${id(2)}' where id = v_dept and head_employee_id is null;
  perform app.run_employee_daily_job(true);
end $$;`);
process.stdout.write(sqlLines.join('\n') + '\n');
