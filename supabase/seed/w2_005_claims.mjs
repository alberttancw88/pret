// Generates the W2-005 synthetic block of supabase/seed.sql (dev / staging only — PDPA): bank details and sample claims for the
// sample employees SMP-01 … SMP-08 ONLY (never INT-001 or any non-sample employee). Account numbers are obviously fake
// (99000000000n) and are encrypted with THIS environment's field key exactly as the app does (ADR-0003: AES-256-GCM, AAD
// table:column:rowId, HMAC blind index 'bank_account'), so the ciphertext is only usable with the key it was generated with.
// Regenerate per environment:   node --env-file=.env.local supabase/seed/w2_005_claims.mjs > /tmp/w2_005_seed.sql
// The script never prints key material or plaintext account numbers.
import { registerHooks } from 'node:module';

registerHooks({
  resolve(specifier, context, next) {
    try { return next(specifier, context); } catch (e) {
      if (specifier.startsWith('.') && !/\.[cm]?[jt]s$/.test(specifier)) return next(`${specifier}.ts`, context);
      throw e;
    }
  },
});
const fc = await import('../../src/server/crypto/field-crypto.ts');
const raw = process.env.PRET_FIELD_KEY_V1;
if (!raw) { console.error('PRET_FIELD_KEY_V1 is not set'); process.exit(2); }
const v1 = fc.parseKey(raw, 'PRET_FIELD_KEY_V1');
const ring = { currentKeyId: 1, keys: new Map([[1, v1]]), blindIndexKey: process.env.PRET_BLIND_INDEX_KEY ? fc.parseKey(process.env.PRET_BLIND_INDEX_KEY, 'PRET_BLIND_INDEX_KEY') : fc.deriveBlindIndexKey(v1) };
const hex = (b) => `'\\x${b.toString('hex')}'`;
const emp = (n) => `00000000-0000-4000-8000-0000000e000${n}`;
const bankRow = (n) => `00000000-0000-4000-8000-0000000eb00${n}`;
const proof = (n) => `00000000-0000-4000-8000-0000000ef00${n}`;

// bank transfer (synthetic): SMP-01, SMP-03, SMP-04, SMP-08 · cheque: SMP-02 · cash: SMP-07 (D23 section)
const transfer = [1, 3, 4, 8];
const rows = transfer.map((n) => {
  const acct = `9900000000${String(n).padStart(2, '0')}`;
  return { n, enc: fc.encryptField(ring, acct, { table: 'employee_bank_accounts', column: 'account_no_enc', rowId: bankRow(n) }),
           bidx: fc.blindIndex(ring, 'bank_account', acct), last4: acct.slice(-4) };
});

process.stdout.write(`-- ===========================================================================
-- W2-005 (synthetic): bank details and sample claims for SMP-01 … SMP-08 ONLY (dev). Never INT-001 or any non-sample employee.
-- Generated by supabase/seed/w2_005_claims.mjs — account ciphertext is valid only with the key of the environment it was
-- generated for (pret-dev). Account numbers 99000000000n, merchants "… (TEST)", receipt nos. "TEST-…" are fake. Receipt and
-- bank-proof files are registry rows only (no Storage object — downloads of them 404 on dev). Dates are relative; idempotent.
-- ===========================================================================
do $$
declare
  v_sys uuid := '00000000-0000-0000-0000-000000000001'; v_today date := app.today_myt(); v_y int := extract(year from app.today_myt())::int;
  v_bank uuid := (select id from app.banks where is_active order by code limit 1);
  c uuid; t uuid; f uuid;
begin
  if not exists (select 1 from app.employees where employee_no = 'SMP-01') then return; end if;
  if exists (select 1 from app.claims x join app.employees e on e.id = x.employee_id where e.employee_no like 'SMP-%') then return; end if;
  perform set_config('app.actor_label', 'seed:w2-005', true);
  -- bank details (D15 history rows; verified by the PRET System actor)
${rows.map((r) => `  insert into app.files (id, bucket, storage_path, subject, owner_employee_id, data_category, original_name, mime_type, size_bytes, status, created_by)
  values ('${proof(r.n)}', 'employee-files', 'emp/${emp(r.n)}/docs/seed/${proof(r.n)}.pdf', 'employee_document', '${emp(r.n)}', 'bank', 'bank-proof-sample.pdf',
          'application/pdf', 1000, 'active', v_sys) on conflict do nothing;
  insert into app.employee_bank_accounts (id, employee_id, payment_method, bank_id, account_type, account_no_enc, account_no_last4, account_no_bidx,
                                          account_holder_name, proof_file_id, effective_from, verified_by)
  values ('${bankRow(r.n)}', '${emp(r.n)}', 'bank_transfer', v_bank, 'savings', ${hex(r.enc)}, '${r.last4}', ${hex(r.bidx)},
          (select upper(full_name) from app.employees where id = '${emp(r.n)}'), '${proof(r.n)}', v_today - 200, v_sys) on conflict do nothing;`).join('\n')}
  insert into app.employee_bank_accounts (id, employee_id, payment_method, effective_from, verified_by)
  values ('${bankRow(2)}', '${emp(2)}', 'cheque', v_today - 200, v_sys), ('${bankRow(7)}', '${emp(7)}', 'cash', v_today - 200, v_sys) on conflict do nothing;

  -- 1. SMP-03 New claim (2 lines: taxi + mileage 42.5 km × RM 0.500 = RM 21.25 (D31))
  insert into app.claims (claim_no, employee_id, title, project_ref) values (private.next_doc_no('CL', v_y), '${emp(3)}', 'Client visits (sample)', 'SAMPLE-PROJ')
  returning id into c;
  insert into app.claim_lines (claim_id, employee_id, line_no, category_id, transaction_date, description, receipt_no, amount_incl_sst, sst_amount)
  select c, '${emp(3)}', 1, k.id, v_today - 5, 'Taxi to client (sample)', 'TEST-RCPT-3001', 32.50, 0 from app.claim_categories k where k.code = 'TRV-TAXI';
  insert into app.claim_lines (claim_id, employee_id, line_no, category_id, transaction_date, from_place, to_place, purpose, distance_km, rate_per_km, amount_incl_sst)
  select c, '${emp(3)}', 2, k.id, v_today - 4, 'Office (sample)', 'Client site (sample)', 'Site visit', 42.5, 0.500, 21.25 from app.claim_categories k where k.code = 'EMP-TRANS';
  perform app.claim_event(c, 'Created', null, 'new');

  -- 2. Submitted claims (SMP-04 office supplies with SST; SMP-05 medical within the RM 300 limit) — one claim_pool task each
  for f in select unnest(array['${emp(4)}', '${emp(5)}']::uuid[]) loop
    insert into app.claims (claim_no, employee_id, title) values (private.next_doc_no('CL', v_y), f,
      case when f = '${emp(4)}' then 'Office supplies (sample)' else 'Clinic visit (sample)' end) returning id into c;
    insert into app.claim_lines (claim_id, employee_id, line_no, category_id, transaction_date, description, merchant, receipt_no, amount_incl_sst, sst_amount)
    select c, f, 1, k.id, v_today - 3, case when f = '${emp(4)}' then 'Printer paper and toner (sample)' else 'GP consultation (sample)' end,
           case when f = '${emp(4)}' then 'Kedai Alat Tulis Contoh (TEST)' else 'Klinik Contoh (TEST)' end,
           'TEST-RCPT-' || right(f::text, 4), case when f = '${emp(4)}' then 85.40 else 120.00 end, case when f = '${emp(4)}' then 4.84 else 0 end
      from app.claim_categories k where k.code = case when f = '${emp(4)}' then 'OFFICE' else 'MEDICAL' end;
    insert into app.files (bucket, storage_path, subject, owner_employee_id, data_category, original_name, mime_type, size_bytes, status, created_by)
    values ('claim-files', 'emp/' || f || '/claims/seed/' || c || '.jpg', 'claim_receipt', f, case when f = '${emp(5)}' then 'health'::app.data_category end,
            'receipt-sample.jpg', 'image/jpeg', 1000, 'active', v_sys) returning id into t;
    insert into app.claim_line_files (claim_line_id, file_id) select l.id, t from app.claim_lines l where l.claim_id = c;
    update app.claims set status = 'submitted', submitted_at = now() - interval '2 days' where id = c;
    insert into app.approval_tasks (subject_type, claim_id, subject_employee_id, level, source, routing_note)
    values ('claim', c, f, 1, 'claim_pool', 'Sample data — approver has no portal account; any Admin or Super Admin may decide');
    perform app.claim_event(c, 'Submitted', 'new', 'submitted');
  end loop;

  -- 3. Approved claims awaiting the month-end batch (SMP-01 software, SMP-08 client meal) and a Rejected one (SMP-07 parking)
  for f in select unnest(array['${emp(1)}', '${emp(8)}', '${emp(7)}']::uuid[]) loop
    insert into app.claims (claim_no, employee_id, title) values (private.next_doc_no('CL', v_y), f,
      case f when '${emp(1)}' then 'Software subscription (sample)' when '${emp(8)}' then 'Client lunch (sample)' else 'Parking (sample)' end) returning id into c;
    insert into app.claim_lines (claim_id, employee_id, line_no, category_id, transaction_date, description, merchant, client_attendees, receipt_no, amount_incl_sst, sst_amount)
    select c, f, 1, k.id, v_today - 10, 'Sample expense', 'Syarikat Contoh (TEST)', case when f = '${emp(8)}' then 'Sample Client Sdn Bhd (TEST), 2 pax' end,
           'TEST-RCPT-' || right(f::text, 4) || '-B', case f when '${emp(1)}' then 59.90 when '${emp(8)}' then 245.60 else 80.00 end,
           case f when '${emp(1)}' then 3.39 when '${emp(8)}' then 13.90 else 0 end
      from app.claim_categories k where k.code = case f when '${emp(1)}' then 'SOFTWARE' when '${emp(8)}' then 'MEAL-CUST' else 'PARKING' end;
    insert into app.files (bucket, storage_path, subject, owner_employee_id, original_name, mime_type, size_bytes, status, created_by)
    values ('claim-files', 'emp/' || f || '/claims/seed/' || c || '.jpg', 'claim_receipt', f, 'receipt-sample.jpg', 'image/jpeg', 1000, 'active', v_sys) returning id into t;
    insert into app.claim_line_files (claim_line_id, file_id) select l.id, t from app.claim_lines l where l.claim_id = c;
    update app.claims set status = 'submitted', submitted_at = now() - interval '8 days' where id = c;
    perform app.claim_event(c, 'Submitted', 'new', 'submitted');
    -- a recorded system decision (seed only): task decided in this transaction, then the claim follows (transition guard)
    insert into app.approval_tasks (subject_type, claim_id, subject_employee_id, level, source, status, acting_as, decided_at, decided_by_name, decision_comment, routing_note)
    values ('claim', c, f, 1, 'claim_pool', case when f = '${emp(7)}' then 'rejected' else 'approved' end::app.task_status, 'system_auto', now(), 'Seed (sample)',
            case when f = '${emp(7)}' then 'Season parking is paid by the company (sample)' end, 'Sample data');
    if f = '${emp(7)}' then
      update app.claims set status = 'rejected', reject_reason = 'Season parking is paid by the company (sample)' where id = c;
      perform app.claim_event(c, 'Rejected', 'submitted', 'rejected', 'system_auto', 'Season parking is paid by the company (sample)');
    else
      update app.claims set status = 'approved' where id = c;
      update app.claim_lines l set tax_treatment_snapshot = k.tax_treatment, gl_account_snapshot = k.gl_account_code
        from app.claim_categories k where k.id = l.category_id and l.claim_id = c;
      perform app.claim_event(c, 'Approved', 'submitted', 'approved', 'system_auto');
    end if;
  end loop;
end $$;
`);
